"""Domain and response models for Sarvam Saaras v4 and 105B adapters."""

from typing import Optional, Dict, Any
from pydantic import BaseModel, Field

class TranscriptResponse(BaseModel):
    """Validated transcript object returned by Saaras v4 STT."""
    transcript: str = Field(..., description="Transcribed spoken text")
    language_code: Optional[str] = Field(None, description="e.g. 'hi-IN', 'te-IN', 'en-IN'")
    mode: str = Field(..., description="transcription mode: 'transcribe', 'codemix', etc.")
    audio_hash: str = Field(..., description="SHA-256 hash of input audio bytes")
    cached: bool = False
    request_id: Optional[str] = None
    latency_ms: Optional[float] = None
    raw_response: Dict[str, Any] = Field(default_factory=dict)

class TransferProposal(BaseModel):
    """
    Structured proposal generated by Sarvam 105B.
    CRITICAL: This is only a candidate proposal passed to SahiGuard.
    It CANNOT execute transfers directly.
    """
    amount_inr: int = Field(..., gt=0, description="Proposed amount in integer INR (> 0)")
    payee: str = Field(..., min_length=1, description="Target recipient name, UPI ID or phone")
    extracted_context: Optional[str] = Field(None, description="Spoken context explanation from audio/prompt")
    raw_arguments: Dict[str, Any] = Field(default_factory=dict)

class SarvamChatResponse(BaseModel):
    """Response object from Sarvam 105B Chat Completions."""
    proposal: Optional[TransferProposal] = None
    message_content: Optional[str] = None
    tool_call_id: Optional[str] = None
    cached: bool = False
    prompt_tokens: Optional[int] = None
    completion_tokens: Optional[int] = None
    latency_ms: Optional[float] = None
    raw_response: Dict[str, Any] = Field(default_factory=dict)
